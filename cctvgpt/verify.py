"""SR-4: verification of a clip's origin.

Anyone can submit a file. Checks, in order:
  1. Embedded signed provenance manifest: is the signature valid, and does the
     video stream still hash to the value in the manifest?
  2. Registry lookup by stream hash (catches clips whose metadata was stripped
     but whose video stream is untouched).
  3. Invisible watermark: recovers the clip token even after re-encoding or
     resizing, then looks the clip up in the registry.
  4. Visible label presence.

A negative result never proves a video is real; the report says so.
"""

from __future__ import annotations

import tempfile
from pathlib import Path

from .context import Platform
from .safeguards import provenance
from .safeguards.label import label_score
from .video_io import probe_video, read_frames, read_tags, stream_sha256

NEGATIVE_CAVEAT = (
    "No platform marks were found. This does NOT mean the video is real: it may come from another "
    "generator, or marks may have been destroyed by cropping or heavy editing."
)


def _public_clip(clip: dict | None, full: bool) -> dict | None:
    if not clip:
        return None
    out = {"clip_id": clip["id"], "created_at": clip["created_at"], "renderer_version": clip["renderer_version"], "status": clip["status"]}
    cid = clip["customer_id"]
    out["customer_id"] = cid if full else (cid[:8] + "..." if cid else None)
    return out


def verify_file(platform: Platform, path: Path, full_details: bool = False) -> dict:
    path = Path(path)
    st = platform.store
    report: dict = {"synthetic_platform_origin": False, "verdict": "no_platform_marks_found", "checks": {}}
    checks = report["checks"]
    info = probe_video(path)
    if info is None:
        report["verdict"] = "unreadable"
        report["message"] = "The file could not be read as a video."
        return report
    checks["video"] = {k: info.get(k) for k in ("codec_name", "width", "height")}

    # 1. Embedded provenance
    envelope = provenance.decode_from_container(read_tags(path).get("comment"))
    manifest_clip = None
    sig_ok = False
    stream_ok = None
    try:
        s_hash = stream_sha256(path)
    except Exception:
        s_hash = None
    if envelope is None:
        checks["provenance"] = {"present": False}
    else:
        sig = provenance.verify_envelope(envelope, platform.keys)
        sig_ok = sig.valid
        m = envelope.get("manifest", {})
        stream_ok = bool(s_hash) and m.get("content", {}).get("video_stream_sha256") == s_hash
        manifest_clip = st.clip(m.get("clip_id", "")) if sig_ok else None
        checks["provenance"] = {
            "present": True,
            "signature_valid": sig_ok,
            "signature_detail": sig.reason,
            "video_stream_matches_manifest": stream_ok,
            "manifest": {k: m.get(k) for k in ("clip_id", "created_at", "claim_generator", "generator", "declared_use", "synthetic", "visible_label", "disclaimer")} if sig_ok else None,
        }
        if sig_ok and full_details:
            checks["provenance"]["manifest"]["customer_id"] = m.get("customer_id")

    # 2. Registry lookup by stream hash
    by_hash = st.clip_by_stream_hash(s_hash) if s_hash else None
    checks["registry_stream_match"] = bool(by_hash)

    # 3. Watermark
    frames = read_frames(path, max_frames=240)
    det = platform.watermarker.detect(frames)
    by_token = st.clip_by_token(det.token) if det.present else None
    checks["watermark"] = {**det.to_dict(), "registered_clip_found": bool(by_token)}
    checks["watermark"].pop("token", None)

    # 4. Visible label
    if frames:
        sample = frames[:: max(1, len(frames) // 8)]
        checks["visible_label_detected"] = max(label_score(f) for f in sample) >= 0.5
    else:
        checks["visible_label_detected"] = False

    clip = manifest_clip or by_hash or by_token
    if sig_ok and stream_ok and manifest_clip:
        report["verdict"] = "verified_platform_original"
        report["message"] = "Signed provenance is valid and the video stream is unmodified. This is synthetic content generated by the platform."
    elif by_hash:
        report["verdict"] = "platform_original_metadata_altered"
        report["message"] = "The video stream exactly matches a platform clip, but its provenance metadata is missing or altered. Synthetic content."
    elif by_token:
        report["verdict"] = "platform_origin_modified"
        report["message"] = "The invisible watermark identifies this as a platform clip that has since been modified (e.g. re-encoded, resized or edited). Synthetic content."
    elif sig_ok:
        report["verdict"] = "platform_manifest_stream_modified"
        report["message"] = "A valid platform manifest is attached but the video stream no longer matches it. Treat as modified synthetic content."
    elif envelope is not None:
        report["verdict"] = "invalid_provenance_claim"
        report["message"] = "The file claims platform provenance but the signature is invalid or the clip is unknown. The claim cannot be trusted."
    else:
        report["message"] = NEGATIVE_CAVEAT
    report["synthetic_platform_origin"] = clip is not None or sig_ok
    report["clip"] = _public_clip(clip, full_details)
    report["limitations"] = (
        "Watermarks and labels can be degraded, cropped or covered by a determined bad actor. "
        "These checks make provenance checkable; they do not make removal impossible."
    )
    return report


def verify_upload(platform: Platform, data: bytes, filename: str = "upload.mp4", full_details: bool = False) -> dict:
    suffix = Path(filename).suffix or ".mp4"
    with tempfile.NamedTemporaryFile(suffix=suffix, delete=True) as tf:
        tf.write(data)
        tf.flush()
        return verify_file(platform, Path(tf.name), full_details)
